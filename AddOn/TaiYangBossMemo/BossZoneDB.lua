local function norm(n)
    if type(n)~="string" then return "" end
    return string.lower((string.gsub(n,"^%s*(.-)%s*$","%1")))
end
local function fromAtlasLoot(name)
    if type(AtlasLoot_TableNames)~="table" then return nil,nil end
    local found=nil
    local seen={}
    -- AtlasLootBossButtons tracks instance menu entries; TableNames holds localized titles.
    if type(AtlasLootBossButtons)~="table" then return nil,nil end
    for _,buttons in pairs(AtlasLootBossButtons) do
        if type(buttons)=="table" then
            for _,id in pairs(buttons) do
                if type(id)=="string" and not seen[id] then
                    seen[id]=true
                    local record=AtlasLoot_TableNames[id]
                    local title=type(record)=="table" and record[1] or nil
                    if type(title)=="string" then
                        local at=string.find(title," - ",1,true)
                        if at then
                            local zone=string.sub(title,1,at-1)
                            local boss=string.sub(title,at+3)
                            -- Optional labels such as (Rare) are not part of UnitName.
                            boss=string.gsub(boss,"%s+%([^%(%)]+%)$","")
                            if norm(boss)==name then
                                if found and found~=zone then return nil,"ambiguous" end
                                found=zone
                            end
                        end
                    end
                end
            end
        end
    end
    return found,found and "atlasloot" or nil
end
function DB.FindByBossName(value)
    local name=norm(value)
    if name=="" then return nil,nil end
    local zone,why=fromAtlasLoot(name)
    if zone or why=="ambiguous" then return zone,why end
    if conflicted[name] then return nil,"ambiguous" end
    return builtIn[name],builtIn[name] and "built-in" or nil
end
